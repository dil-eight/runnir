package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

const generatedBy = "scripts/update-notices.sh"

type component struct {
	Name    string   `json:"name"`
	Version string   `json:"version"`
	License string   `json:"license"`
	Source  string   `json:"source"`
	Texts   []string `json:"texts"`
	files   []file
}

type group struct {
	Name       string      `json:"name"`
	Components []component `json:"components"`
}

type catalog struct {
	GeneratedBy string            `json:"generatedBy"`
	Groups      []group           `json:"groups"`
	Texts       map[string]string `json:"texts"`
}

// textID: the first 12 hex digits of the text's SHA-256, so that a text
// shared by many components is stored once.
func textID(text string) string {
	sum := sha256.Sum256([]byte(text))
	return hex.EncodeToString(sum[:])[:12]
}

// clean trims trailing white space from every line and the text, so that
// the same license copied with different line ends counts as one text.
func clean(text string) string {
	lines := strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n")
	for i, line := range lines {
		lines[i] = strings.TrimRight(line, " \t\r")
	}
	return strings.Trim(strings.Join(lines, "\n"), "\n")
}

// build fills in the components' text ids and the text pool.
func build(groups []group) catalog {
	c := catalog{GeneratedBy: generatedBy, Groups: groups, Texts: map[string]string{}}
	for gi := range c.Groups {
		for ci := range c.Groups[gi].Components {
			comp := &c.Groups[gi].Components[ci]
			comp.Texts = nil
			seen := map[string]bool{}
			for _, f := range comp.files {
				text := clean(f.text)
				id := textID(text)
				c.Texts[id] = text
				if !seen[id] {
					seen[id] = true
					comp.Texts = append(comp.Texts, id)
				}
			}
		}
	}
	return c
}

func renderJSON(c catalog) ([]byte, error) {
	var b bytes.Buffer
	encoder := json.NewEncoder(&b)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(c); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

const rule = "================================================================================"

// renderText writes one group as plain text: every distinct text once,
// after the components it covers.
func renderText(c catalog, groupName, product string) ([]byte, error) {
	var g *group
	for i := range c.Groups {
		if c.Groups[i].Name == groupName {
			g = &c.Groups[i]
		}
	}
	if g == nil {
		return nil, fmt.Errorf("no group %q", groupName)
	}
	users := map[string][]component{}
	for _, comp := range g.Components {
		for _, id := range comp.Texts {
			users[id] = append(users[id], comp)
		}
	}
	ids := make([]string, 0, len(users))
	for id := range users {
		ids = append(ids, id)
	}
	// By the first component that uses a text, then by id.
	sort.Slice(ids, func(i, j int) bool {
		a, b := users[ids[i]][0].Name, users[ids[j]][0].Name
		if a != b {
			return a < b
		}
		return ids[i] < ids[j]
	})
	var b bytes.Buffer
	fmt.Fprintf(&b, "Third-party software in %s\n", product)
	fmt.Fprintf(&b, "Generated by %s; do not edit.\n\n", generatedBy)
	fmt.Fprintf(&b, "%s includes the components below. Each license or notice text follows the components it applies to.\n", product)
	for _, id := range ids {
		b.WriteString("\n" + rule + "\n")
		for _, comp := range users[id] {
			fmt.Fprintf(&b, "%s %s (%s)\n  Source: %s\n", comp.Name, comp.Version, comp.License, comp.Source)
		}
		b.WriteString(strings.Repeat("-", len(rule)) + "\n")
		b.WriteString(c.Texts[id] + "\n")
	}
	return b.Bytes(), nil
}
